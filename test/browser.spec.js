import { test, expect } from '@playwright/test';

async function login(page, account) {
  await page.goto('/#login');
  await page.getByLabel('Email address').fill(account+'@neighborhood.test');
  await page.getByLabel('Password',{exact:true}).fill('local-fixture-pass');
  await page.getByRole('button',{name:'Sign in',exact:true}).click();
  await expect(page.getByRole('heading',{name:'Your neighborhood'})).toBeVisible();
}
async function logout(page) {
  await page.goto('/#account');
  await page.getByRole('button',{name:'Sign out'}).click();
  await expect(page.getByRole('heading',{name:'Good things happen close to home.'})).toBeVisible();
}

test('mobile landing and resident request-to-reply-to-message flow',async({page})=>{
  await page.setViewportSize({width:390,height:844});
  const errors = [];
  page.on('pageerror',(e)=>errors.push(e.message));
  await page.goto('/');
  await expect(page.getByRole('heading',{name:'Good things happen close to home.'})).toBeVisible();
  expect(await page.evaluate(()=>document.documentElement.scrollWidth)).toBe(390);
  await page.screenshot({path:'test-results/landing-mobile.png',fullPage:true});
  await login(page,'ava');
  await page.screenshot({path:'test-results/feed-mobile.png',fullPage:true});
  await page.getByRole('link',{name:'Requests',exact:true}).click();
  await page.getByRole('link',{name:'Request a service'}).click();
  await page.getByLabel('Title').fill('Need help repairing porch steps');
  await page.getByLabel('Details').fill('A loose step needs repair. Any local recommendations?');
  await page.getByRole('button',{name:'Publish post'}).click();
  await expect(page.getByRole('heading',{name:'Need help repairing porch steps'})).toBeVisible();
  const post = new URL(page.url()).hash;
  await logout(page);
  await login(page,'luis');
  await page.goto('/'+post);
  await page.getByLabel('Your reply').fill('My local business is available for a conversation.');
  await page.getByLabel('Reply as').selectOption({label:'Juniper Home Repair'});
  await page.getByRole('button',{name:'Post reply'}).click();
  await expect(page.getByText('Business affiliation',{exact:true})).toBeVisible();
  await page.getByRole('link',{name:'Message Ava M.'}).click();
  await page.getByLabel('Your message').fill('Would Saturday work for a look at the steps?');
  await page.getByRole('button',{name:'Send message'}).click();
  await expect(page.getByText('Would Saturday work for a look at the steps?')).toBeVisible();
  await logout(page);
  await login(page,'ava');
  await page.getByRole('link',{name:'Messages',exact:true}).click();
  await page.getByRole('link',{name:/Luis G\./}).click();
  await expect(page.getByText('Would Saturday work for a look at the steps?')).toBeVisible();
  await page.getByRole('button',{name:'Block messages'}).click();
  await expect(page.getByText('You blocked messages from this neighbor.')).toBeVisible();
  expect(await page.evaluate(()=>document.documentElement.scrollWidth)).toBe(390);
  expect(errors).toEqual([]);
});

test('desktop review submission, removal, independent appeal, and business vetting',async({page})=>{
  await page.setViewportSize({width:1440,height:980});
  const errors = [];
  page.on('pageerror',(e)=>errors.push(e.message));
  await page.goto('/');
  await expect(page.getByRole('heading',{name:'Good things happen close to home.'})).toBeVisible();
  await page.screenshot({path:'test-results/landing-desktop.png',fullPage:true});
  await login(page,'jamal');
  await page.screenshot({path:'test-results/feed-desktop.png',fullPage:true});
  await page.getByRole('link',{name:'Businesses',exact:true}).click();
  await page.getByRole('link',{name:'Juniper Home Repair',exact:true}).click();
  await page.getByLabel('Rating').selectOption('4');
  await page.getByLabel('Your review').fill('I hired this fixture business and had a satisfactory experience. This entry is for testing.');
  await page.getByLabel('I am describing my own firsthand experience.').check();
  await page.getByRole('button',{name:'Submit for review'}).click();
  await expect(page.getByText('Review sent for human moderation.')).toBeVisible();
  await expect(page.getByText('No published reviews yet.')).toBeVisible();
  await logout(page);
  await login(page,'rina');
  await page.getByRole('link',{name:'Moderation',exact:true}).click();
  await page.getByText('Record review decision').click();
  await page.getByRole('combobox',{name:'Decision',exact:true}).selectOption('removed');
  await page.getByLabel('Reason shown to the author').fill('Fixture removal so we can exercise the appeals path.');
  await page.getByRole('button',{name:'Save decision'}).click();
  await expect(page.getByText('Review decision recorded.')).toBeVisible();
  await logout(page);
  await login(page,'jamal');
  await page.goto('/#my-reviews');
  await page.getByText('Appeal decision',{exact:true}).click();
  await page.getByLabel('Why should an independent moderator reconsider?').fill('This is a test of the independent review appeal flow.');
  await page.getByRole('button',{name:'Submit appeal'}).click();
  await expect(page.getByText('Appeal pending',{exact:true})).toBeVisible();
  await logout(page);
  await login(page,'luis');
  await page.goto('/#manage');
  await page.getByText('Apply for vetting').click();
  await page.getByLabel('Legal business name').fill('Synthetic Juniper Home Repair');
  await page.getByLabel('Public business registration or directory reference').fill('Synthetic registration number');
  await page.getByLabel('Public contact reference').fill('Synthetic public phone');
  await page.getByRole('button',{name:'Send for vetting'}).click();
  await expect(page.getByText('Vetting application under review')).toBeVisible();
  await logout(page);
  await login(page,'devon');
  await page.goto('/#moderation');
  await page.getByRole('combobox',{name:'Decision',exact:true}).selectOption('restored');
  await page.getByLabel('Reason shown to the author').fill('Independent fixture reconsideration recorded.');
  await page.getByRole('button',{name:'Save appeal decision'}).click();
  await expect(page.getByText('Appeal decision recorded.')).toBeVisible();
  await page.getByText('Record vetting decision').click();
  await page.getByRole('combobox',{name:'Decision',exact:true}).selectOption('approved');
  await page.getByLabel('Independent identity evidence').fill('Synthetic registry identity check');
  await page.getByLabel('Independent control evidence').fill('Synthetic business contact check');
  await page.getByLabel('License and insurance check').fill('Synthetic credentials check');
  await page.getByLabel('I personally completed and documented these checks.').check();
  await page.getByLabel('Decision reason shown to the business').fill('Approval in the isolated fixture only.');
  await page.getByRole('button',{name:'Save vetting decision'}).click();
  await expect(page.getByText('Vetting decision recorded.')).toBeVisible();
  await page.getByRole('link',{name:'Businesses',exact:true}).click();
  await page.getByRole('link',{name:'Juniper Home Repair',exact:true}).click();
  await expect(page.getByText('I hired this fixture business', {exact:false})).toBeVisible();
  await expect(page.getByText('Verified Business',{exact:true})).toHaveCount(0);
  expect(errors).toEqual([]);
});
